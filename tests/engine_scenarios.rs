/// `EXE_SUFFIX` and the platform separator make a Windows-built path spell
/// `<SCRIPT_DIR>/bin\ffmpeg.exe` where every scenario above says
/// `<SCRIPT_DIR>/bin/ffmpeg`. Undo both so one set of scenarios covers every
/// platform. A no-op on Linux: `EXE_SUFFIX` is empty there and nothing else
/// in an argv contains a backslash.
fn normalize_tool_path(arg: &str) -> String {
    let stripped = arg
        .strip_suffix(std::env::consts::EXE_SUFFIX)
        .unwrap_or(arg);
    if cfg!(windows) {
        stripped.replace('\\', "/")
    } else {
        stripped.to_string()
    }
}

#[test]
fn every_scenario_produces_its_recorded_argv_and_exit() {
    let bin_dir = Path::new("<SCRIPT_DIR>/bin");
    let all = scenarios();
    let mut failures = Vec::new();

    for scenario in &all {
        let output_dir = scenario.output_dir.map(Path::new);
        let urls: Vec<String> = scenario.urls.iter().map(|u| u.to_string()).collect();
        let actual: Vec<String> = build_args(&scenario.options, bin_dir, output_dir, &urls)
            .into_iter()
            .map(|a| normalize_tool_path(&a.to_string_lossy()))
            .collect();
        let expected: Vec<String> = scenario.argv.iter().map(|s| s.to_string()).collect();
        if actual != expected {
            let first = actual
                .iter()
                .zip(&expected)
                .position(|(a, e)| a != e)
                .unwrap_or(actual.len().min(expected.len()));
            failures.push(format!(
                "{}: argv differs at position {first}\n  expected: {expected:?}\n  actual:   {actual:?}",
                scenario.name
            ));
        }

        let implied = match classify_exit(scenario.fake_exit) {
            Outcome::Completed | Outcome::StoppedAsConfigured => 0,
            Outcome::Failed(c) => c,
        };
        if implied != scenario.exit {
            failures.push(format!(
                "{}: yt-dlp exit {} should end as {}, engine says {implied}",
                scenario.name, scenario.fake_exit, scenario.exit
            ));
        }
    }

    assert!(
        failures.is_empty(),
        "{} of {} scenarios failed:\n{}",
        failures.len(),
        all.len(),
        failures.join("\n")
    );
}
