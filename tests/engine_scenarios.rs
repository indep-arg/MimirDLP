//! Pins `engine::build_args` and `engine::classify_exit` to a fixed set of
//! configurations, so a behaviour change shows up as a reviewed diff to
//! `scenarios()` below instead of a silent regression. Every fixture here is
//! plain, typed Rust: there is no external harness and nothing is read from
//! disk at test time.

use std::path::Path;

